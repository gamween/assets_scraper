// Compiles the class-merge tables of `cn` for the app's type scale into src/components/common/cn-tables.ts.
//   node scripts/build-cn-tables.mjs    write the tables (pnpm build:cn): after a cn upgrade or a change to cn-config.mjs
// The module is committed. It only changes with those two, and scripts/build-cn-tables.test.mjs fails while it is out
// of date, so the page never runs the cn compiler: it ships the engine and these tables, not the compiler and the
// 45 KB default config it would otherwise compile on the first call.
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "cn/build";
import { writeAtomic } from "./write-atomic.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
export const CONFIG = path.join(ROOT, "src/components/common/cn-config.mjs");
export const TABLES = path.join(ROOT, "src/components/common/cn-tables.ts");

const HEADER = "// Generated by scripts/build-cn-tables.mjs from cn-config.mjs (pnpm build:cn). Do not edit.\n";

/** The tables module for the installed cn and the config, as the committed file should read. */
export async function tablesSource() {
  const dir = await mkdtemp(path.join(tmpdir(), "cn-tables-"));
  try {
    // Every class group, not the subset the sources use today: the tables cannot go stale when a component starts using
    // a utility no build has seen, and a class name put together at runtime still merges.
    const { source } = await build({ cwd: ROOT, config: CONFIG, out: path.join(dir, "cn-tables.ts"), full: true });
    // cn's own header names its CLI; this one names the script that owns the file.
    return HEADER + source.replace(/^(?:\/\/.*\n)+/, "");
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeAtomic(TABLES, await tablesSource());
  console.log(`cn tables written to ${path.relative(ROOT, TABLES)}`);
}
